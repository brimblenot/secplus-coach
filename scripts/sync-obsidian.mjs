// sync-obsidian.mjs
// Reads live Sec+ progress from the app's database and writes a Markdown
// progress dashboard into an Obsidian vault. Run: `npm run kb:sync`
//
// Output location (first match wins):
//   1. --out <path> CLI flag
//   2. OBSIDIAN_VAULT env var (points at the vault ROOT; file written inside it)
//   3. ./obsidian-export/  (fallback, created next to the app)
//
// Data source (first match wins):
//   1. DATABASE_URL in .env.local  -> live Postgres (same DB the app uses)
//   2. ./data/coach.db             -> local SQLite snapshot (offline fallback)

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')

const DOMAIN_NAMES = {
  1: 'General Security Concepts',
  2: 'Threats, Vulnerabilities & Mitigations',
  3: 'Security Architecture',
  4: 'Security Operations',
  5: 'Security Program Management & Oversight',
}

// ── Resolve output path ──────────────────────────────────────────────
function outDir() {
  const flagIdx = process.argv.indexOf('--out')
  if (flagIdx !== -1 && process.argv[flagIdx + 1]) return process.argv[flagIdx + 1]
  if (process.env.OBSIDIAN_VAULT) return process.env.OBSIDIAN_VAULT
  return path.join(ROOT, 'obsidian-export')
}

// ── Load DATABASE_URL from .env.local (no dotenv dependency) ─────────
function loadDatabaseUrl() {
  if (process.env.DATABASE_URL) return process.env.DATABASE_URL
  const envPath = path.join(ROOT, '.env.local')
  if (!fs.existsSync(envPath)) return null
  for (const line of fs.readFileSync(envPath, 'utf8').split('\n')) {
    const m = line.match(/^\s*DATABASE_URL\s*=\s*(.*)\s*$/)
    if (m) return m[1].replace(/^["']|["']$/g, '').trim()
  }
  return null
}

// ── Fetch rows: [{topic_id, topic_name, domain, status, quiz_score, quiz_attempts}] ──
async function fetchProgress() {
  const forceSqlite =
    process.argv.includes('--offline') || process.env.KB_SYNC_OFFLINE === '1'
  const url = forceSqlite ? null : loadDatabaseUrl()
  if (url) {
    const { default: postgres } = await import('postgres')
    const sql = postgres(url, { prepare: false, max: 2, idle_timeout: 10, connect_timeout: 10 })
    try {
      const rows = await sql`
        SELECT topic_id, topic_name, domain, status, quiz_score, quiz_attempts
        FROM topic_progress ORDER BY topic_id`
      return { source: 'live database', rows }
    } finally {
      await sql.end({ timeout: 5 })
    }
  }
  // SQLite fallback (Node 22+ has node:sqlite; else tell the user)
  try {
    const { DatabaseSync } = await import('node:sqlite')
    const db = new DatabaseSync(path.join(ROOT, 'data', 'coach.db'))
    const rows = db
      .prepare(
        `SELECT topic_id, topic_name, domain, status, quiz_score, quiz_attempts
         FROM topic_progress ORDER BY topic_id`,
      )
      .all()
    return { source: 'local coach.db snapshot', rows }
  } catch {
    throw new Error(
      'No DATABASE_URL in .env.local and node:sqlite unavailable. ' +
        'Set DATABASE_URL or run on Node 22+.',
    )
  }
}

// ── Build the dashboard markdown ─────────────────────────────────────
function bar(pct, width = 20) {
  const filled = Math.round((pct / 100) * width)
  return '█'.repeat(filled) + '░'.repeat(width - filled)
}

function buildMarkdown({ source, rows }) {
  const total = rows.length
  const passed = rows.filter((r) => r.status === 'passed')
  const studying = rows.filter((r) => r.status === 'studying')
  const scored = rows.filter((r) => r.quiz_score != null)
  const overallMastery = scored.length
    ? Math.round(scored.reduce((s, r) => s + Number(r.quiz_score), 0) / scored.length)
    : 0
  const pctComplete = total ? Math.round((passed.length / total) * 100) : 0
  const now = new Date().toISOString().slice(0, 16).replace('T', ' ')

  let md = `---
title: Sec+ Progress Dashboard
updated: ${now}
source: ${source}
tags: [dashboard, sec-plus, progress]
---

# 📊 Sec+ Progress Dashboard

> Auto-generated by \`npm run kb:sync\`. Last updated **${now}** from ${source}. Do not edit by hand — rerun the sync.

## Overall
- **Topics passed:** ${passed.length} / ${total}  (${pctComplete}%)
- \`${bar(pctComplete)}\` ${pctComplete}%
- **Average mastery** (scored topics): **${overallMastery}%**
- **Currently studying:** ${studying.map((r) => r.topic_name).join(', ') || '—'}

## By domain
| Domain | Passed | Avg mastery | Progress |
|--------|:------:|:-----------:|----------|
`

  for (const d of [1, 2, 3, 4, 5]) {
    const dt = rows.filter((r) => Number(r.domain) === d)
    if (!dt.length) continue
    const dPassed = dt.filter((r) => r.status === 'passed').length
    const dScored = dt.filter((r) => r.quiz_score != null)
    const dMastery = dScored.length
      ? Math.round(dScored.reduce((s, r) => s + Number(r.quiz_score), 0) / dScored.length)
      : 0
    const dPct = Math.round((dPassed / dt.length) * 100)
    md += `| ${d}. ${DOMAIN_NAMES[d]} | ${dPassed}/${dt.length} | ${dMastery}% | \`${bar(dPct, 12)}\` ${dPct}% |\n`
  }

  // Weakest passed topics (lowest scores) — study targets
  const weakest = [...scored]
    .filter((r) => r.status === 'passed')
    .sort((a, b) => Number(a.quiz_score) - Number(b.quiz_score))
    .slice(0, 8)
  md += `\n## 🎯 Lowest-scoring passed topics (review targets)\n\n`
  md += weakest.length
    ? weakest.map((r) => `- **${r.quiz_score}%** — ${r.topic_name} _(D${r.domain})_`).join('\n')
    : '_None yet._'

  // Full table
  md += `\n\n## All topics\n\n| # | Topic | Domain | Status | Mastery | Attempts |\n|---|-------|:------:|:------:|:-------:|:--------:|\n`
  const statusIcon = { passed: '✅ passed', studying: '📖 studying', pending: '⬜ pending', failed: '❌ failed' }
  for (const r of rows) {
    md += `| ${r.topic_id} | ${r.topic_name} | ${r.domain} | ${statusIcon[r.status] || r.status} | ${
      r.quiz_score != null ? r.quiz_score + '%' : '—'
    } | ${r.quiz_attempts ?? 0} |\n`
  }

  return md
}

// ── Per-topic writeups (for passed topics, from study guides) ────────
const DOMAIN_FOLDER = {
  1: '01 General Security Concepts',
  2: '02 Threats Vulnerabilities and Mitigations',
  3: '03 Security Architecture',
  4: '04 Security Operations',
  5: '05 Security Program Management',
}

function safeName(s) {
  return s.replace(/[\\/:*?"<>|]/g, '-').trim()
}

function writeTopicNotes(rows, dir) {
  const topicsDir = path.join(dir, 'Sec+ Topics')
  fs.mkdirSync(topicsDir, { recursive: true })
  const passed = rows.filter((r) => r.status === 'passed')
  let written = 0
  for (const r of passed) {
    const guidePath = path.join(ROOT, 'study-guides', `${r.topic_id}.md`)
    const guide = fs.existsSync(guidePath) ? fs.readFileSync(guidePath, 'utf8') : ''
    const file = path.join(topicsDir, `${r.topic_id} ${safeName(r.topic_name)}.md`)

    // Preserve any hand-written "## My Notes" section across re-syncs.
    let myNotes = '\n## My Notes\n\n_(your own notes — this section is preserved on re-sync)_\n'
    if (fs.existsSync(file)) {
      const prev = fs.readFileSync(file, 'utf8')
      const m = prev.match(/\n## My Notes\n[\s\S]*$/)
      if (m) myNotes = m[0]
    }

    const domainName = DOMAIN_NAMES[r.domain] || `Domain ${r.domain}`
    const note = `---
title: ${r.topic_name}
topic_id: ${r.topic_id}
domain: ${r.domain}
status: ${r.status}
mastery: ${r.quiz_score ?? ''}
attempts: ${r.quiz_attempts ?? 0}
tags: [sec-plus, topic, domain-${r.domain}]
---

> **Mastery ${r.quiz_score ?? '—'}%** · Domain ${r.domain} — ${domainName} · ${r.quiz_attempts ?? 0} attempt(s) · [[Sec+ Progress Dashboard|↩ Dashboard]]

${guide.trim() || '_(No study guide found for this topic.)_'}
${myNotes}`
    fs.writeFileSync(file, note, 'utf8')
    written++
  }
  return written
}

// ── Main ─────────────────────────────────────────────────────────────
async function main() {
  const data = await fetchProgress()
  const md = buildMarkdown(data)
  const dir = outDir()
  fs.mkdirSync(dir, { recursive: true })
  const file = path.join(dir, 'Sec+ Progress Dashboard.md')
  fs.writeFileSync(file, md, 'utf8')
  const noteCount = writeTopicNotes(data.rows, dir)
  console.log(`✔ Wrote dashboard (${data.rows.length} topics, source: ${data.source})`)
  console.log(`✔ Wrote ${noteCount} topic writeup(s) to "Sec+ Topics/"`)
  console.log(`  → ${file}`)
  if (!process.env.OBSIDIAN_VAULT && process.argv.indexOf('--out') === -1) {
    console.log('\nTip: set OBSIDIAN_VAULT to your vault path so it writes straight into Obsidian, e.g.')
    console.log('  OBSIDIAN_VAULT="C:\\\\path\\\\to\\\\your\\\\vault" npm run kb:sync')
  }
}

main().catch((e) => {
  console.error('✖ sync-obsidian failed:', e.message)
  process.exit(1)
})
